-- order_info
-- 库：order
-- 业务分类：洗水
-- 使用场景：查订单信息

CREATE TABLE `order_info` (
  `out_trade_no` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '交易订单号',
  `parent_no` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '父订单号',
  `order_type` tinyint(255) DEFAULT NULL COMMENT '订单类型 1:普通订单 2:虚拟单',
  `user_id` bigint(11) DEFAULT NULL COMMENT '用户id',
  `distributor_id` bigint(11) DEFAULT NULL COMMENT '商户id',
  `store_id` bigint(11) DEFAULT NULL COMMENT '店铺id',
  `order_amount` decimal(11,2) DEFAULT NULL COMMENT '订单金额',
  `actual_amount` decimal(11,2) DEFAULT NULL COMMENT '实际金额',
  `marketing_detail` json DEFAULT NULL COMMENT '营销详情',
  `status` tinyint(255) DEFAULT NULL COMMENT '订单状态 1:待支付 2:已支付 3:退款中 4:已退款 5:已取消 6:未支付 7:已关闭',
  `trans_type` tinyint(255) DEFAULT NULL COMMENT '交易类型',
  `business_type` smallint(255) DEFAULT NULL COMMENT '业务编号',
  `create_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '订单创建时间',
  `goods_detail` json DEFAULT NULL COMMENT '商品详情',
  `equipment_detail` json DEFAULT NULL COMMENT '设备详情',
  `discount_detail` json DEFAULT NULL COMMENT '优惠详情',
  `member_detail` json DEFAULT NULL COMMENT '会员详情',
  `pay_detail` json DEFAULT NULL COMMENT '支付详情',
  `client_type` tinyint(4) DEFAULT NULL COMMENT '客户端类型',
  `pay_order_no` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '支付单号',
  `sub_order_num` int(2) DEFAULT NULL COMMENT '子单数量',
  `id` bigint(11) NOT NULL auto_increment,
  `remark` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '订单备注',
  `operator` json DEFAULT NULL COMMENT '操作人信息',
  `paid_amount` decimal(11,2) DEFAULT NULL DEFAULT '0.00' COMMENT '已付金额',
  `update_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `create_by` bigint(11) DEFAULT NULL COMMENT '创建人',
  `update_by` bigint(11) DEFAULT NULL COMMENT '修改人',
  `organization_id` bigint(11) DEFAULT NULL COMMENT '组织id',
  `sales_order_no` varchar(50) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '销售单号',
  `extend_str` text CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '业务扩展字段',
  `common_extend` text CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '通用扩展字段',
  `refund_mark` tinyint(4) DEFAULT NULL COMMENT '退款标记,1部分退款,2全部退款',
  `equipment_id` bigint(20) DEFAULT NULL COMMENT '设备id',
  `dealer_order_type` tinyint(4) DEFAULT NULL COMMENT '订单分类(充值订单,消费订单,权益结算订单)',
  `is_wallet_settlement` tinyint(4) DEFAULT NULL COMMENT '是否资金池结算',
  `business_scene_merchant_id` bigint(20) DEFAULT NULL COMMENT '经销商商户id',
  `agent_merchant_id` bigint(20) DEFAULT NULL COMMENT '代理商商户id',
  `open_id` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '从member_detail取open_id存储',
  `def6` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
  `def7` json DEFAULT NULL,
  `def8` json DEFAULT NULL,
  `def9` decimal(11,2) DEFAULT NULL,
  `def10` decimal(11,2) DEFAULT NULL,
  PRIMARY KEY (`id`, `create_time`),
  KEY `idx_agent_merchant_id` (`agent_merchant_id`),
  KEY `idx_business_scene_merchant_id` (`business_scene_merchant_id`),
  KEY `idx_distributor_id_create_time` (`distributor_id`, `create_time`),
  KEY `idx_open_id` (`open_id`),
  UNIQUE KEY `idx_out_trade_no` (`out_trade_no`, `create_time`),
  KEY `idx_utime` (`update_time`),
  KEY `index_create_time` (`create_time`),
  KEY `index_equipment_id` (`equipment_id`),
  KEY `parent_no` (`parent_no`),
  KEY `user_id` (`user_id`)
)
