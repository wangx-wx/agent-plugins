-- refund_order_info
-- 库：order
-- 业务分类：洗水
-- 使用场景：查订单退款信息

CREATE TABLE `refund_order_info` (
  `out_trade_no` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '交易订单号',
  `refund_no` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '退款单号',
  `user_id` bigint(11) DEFAULT NULL COMMENT '用户id',
  `distributor_id` bigint(11) DEFAULT NULL COMMENT '商户id',
  `order_amount` decimal(11,2) DEFAULT NULL COMMENT '订单金额',
  `refund_amount` decimal(11,2) DEFAULT NULL COMMENT '退款金额',
  `refund_detail` json DEFAULT NULL COMMENT '退款详情',
  `status` tinyint(255) DEFAULT NULL COMMENT '退款状态 1:退款中 2:退款成功 3:退款失败',
  `refund_reason` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '退款原因',
  `refund_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '退款发起时间',
  `refund_success_time` timestamp DEFAULT NULL COMMENT '退款成功时间',
  `refund_type` tinyint(255) DEFAULT NULL COMMENT '退款类型 1:自动退款 2:手动退款',
  `goods_detail` json DEFAULT NULL COMMENT '退款商品详情',
  `id` bigint(11) NOT NULL auto_increment,
  `create_by` bigint(11) DEFAULT NULL COMMENT '创建人id',
  `cashier` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '操作人名称',
  `terminal_id` bigint(11) DEFAULT NULL COMMENT '终端设备id',
  `terminal_name` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '终端设备名称',
  `create_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_by` bigint(11) DEFAULT NULL COMMENT '修改人',
  `organization_id` bigint(11) DEFAULT NULL COMMENT '组织id',
  `business_type` smallint(255) DEFAULT NULL,
  `deduction_amount` decimal(11,2) DEFAULT NULL COMMENT '退抵扣金额',
  `store_id` bigint(11) DEFAULT NULL COMMENT '店铺id',
  `refund_order_no` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL DEFAULT '' COMMENT '退款单号（废弃，用refund_no）',
  `remark` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL DEFAULT '' COMMENT '备注',
  `common_extend` json DEFAULT NULL COMMENT '扩展信息',
  `extend_str` varchar(1024) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL COMMENT '业务扩展字段',
  `def1` varchar(256) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
  `refund_source` tinyint(4) DEFAULT NULL COMMENT '退款来源',
  `def3` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
  `def4` bigint(12) DEFAULT NULL,
  `def11` tinyint(4) DEFAULT NULL,
  `def2` tinyint(4) DEFAULT NULL,
  `def13` bigint(20) DEFAULT NULL,
  `def14` bigint(20) DEFAULT NULL,
  `def5` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
  `def6` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL,
  `marketing_detail` json DEFAULT NULL COMMENT '营销详情',
  `def8` json DEFAULT NULL,
  `def9` decimal(11,2) DEFAULT NULL,
  `def10` decimal(11,2) DEFAULT NULL,
  PRIMARY KEY (`id`, `refund_time`),
  KEY `btree` (`distributor_id`, `refund_time`),
  KEY `idx_ctime` (`create_time`),
  KEY `idx_out_trade_no` (`out_trade_no`),
  UNIQUE KEY `idx_refund_no` (`refund_no`, `refund_time`),
  UNIQUE KEY `idx_refund_order_info_id` (`id`, `refund_time`),
  KEY `idx_utime` (`update_time`),
  KEY `refund_order_time_store_idx` (`refund_time`, `store_id`),
  KEY `user_id` (`user_id`)
)
